def test_unreadable_halt_and_pause_files_count_as_present(tmp_path, monkeypatch):
    """S-5: production is fail-closed for these files (halt.json present means halted, a pause
    file that cannot be read means paused). So is the check: a file that exists but cannot be
    read, parsed or shaped as expected counts as present, is graded as usual, and is flagged."""
    mod = load()
    not_json = ("", "{", "[", "null", '"text"', "123")
    cases = [("halt.json", "halt", content) for content in not_json]
    cases += [("pause-902610.json", "pause:902610", content) for content in
              (*not_json, '{"reason": "x"}', '{"magic": 902610, "paused": "yes"}')]
    for name, code, content in cases:
        live, reports = site(tmp_path)
        (live / name).write_text(content, encoding="utf-8")
        touch(live / name, NOW - timedelta(seconds=3700))               # there for over an hour
        findings, _ = look(mod, live, reports, tmp_path)
        assert codes(findings) == {code: True}, (name, content)
        assert findings[0]["unreadable"] is True, (name, content)
    live, reports = site(tmp_path)
    (live / "halt.json").write_text('{"reason": "x"}', encoding="utf-8")      # any object is a halt
    findings, _ = look(mod, live, reports, tmp_path, {"halt": (NOW - timedelta(seconds=3700)).isoformat()})
