def key_of(kind, magic):
    return str(magic) if kind == "runner" else kind


def ago(now, seconds):
    return (now - timedelta(seconds=seconds)).isoformat()


def touch(path, when):
    stamp = when.timestamp()
    os.utime(path, (stamp, stamp))


def generated_reports(now, days=4):
    """The daily-report task's real schedule, not the checker's rule: the report for day X is
    generated at 21:57 UTC on day X+1. The dates whose report exists at `now`."""
    utc = now.astimezone(timezone.utc)
    return [(utc - timedelta(days=n)).date().isoformat() for n in range(1, days + 1)
            if utc >= datetime.combine(utc.date() - timedelta(days=n - 1), time(21, 57), timezone.utc)]


def site(tmp_path, *, root=None, hb_age=5.0, supervisor_age=30.0, halt=None, pauses=(), kill=False, veto=False,
         report=True, registry=True, now=NOW, started=None):
    """A synthetic live directory under a fresh sub-directory (or again under `root`). Ages are
    seconds before `now`: a halt or pause file of age A was written A seconds ago (content and
    modification time). `report` is True (every report the real schedule has generated by
    `now`), False (none) or an explicit list of dates. `started` is when the deployment started
    (the registry's started_utc): three days before `now` unless given."""
    global _SITES
    if root is None:
        _SITES += 1
        root = tmp_path / f"site{_SITES}"
    elif root.exists():
        shutil.rmtree(root)
    def age_of(key):
        return hb_age.get(key, 5.0) if isinstance(hb_age, dict) else hb_age
    data = root / "data"
    live, reports = data / "live", data / "reports"
    live.mkdir(parents=True), (reports / "live").mkdir(parents=True)
    if registry:
        entries = [{"pid": pid, "started_utc": (started or now - timedelta(days=3)).isoformat(),
                    "kind": kind, "magic": magic} for kind, magic, pid in ROLES]
        (live / "instances.json").write_text(json.dumps({"schema_version": 1, "instances": entries}), encoding="utf-8")
    for kind, magic, pid in ROLES:
        (live / f"heartbeat-{key_of(kind, magic)}.json").write_text(
            json.dumps({"runner_alive": True, "ts": ago(now, age_of(key_of(kind, magic))), "pid": pid + 100}),
            encoding="utf-8")
    if supervisor_age is not None:
        (live / "supervisor-state.json").write_text(json.dumps({"last_checked": ago(now, supervisor_age)}), encoding="utf-8")
    if halt is not None:
        (live / "halt.json").write_text(json.dumps(
            {"reason": "component_lost", "owner": "supervisor", "ts": ago(now, halt)}), encoding="utf-8")
        touch(live / "halt.json", now - timedelta(seconds=halt))
    for magic, age in pauses:
        (live / f"pause-{magic}.json").write_text(json.dumps(
            {"magic": magic, "paused": True, "reason": "RECONCILE_MISMATCH", "ts": ago(now, age)}), encoding="utf-8")
        touch(live / f"pause-{magic}.json", now - timedelta(seconds=age))
    if kill:
        (live / "killSwitch").write_text("", encoding="utf-8")
    if veto:
        (live / "halt-risk-veto.json").write_text("{}", encoding="utf-8")
    if report is True:
        report = generated_reports(now)
    for day in report or ():
        (reports / "live" / f"daily-{day}.md").write_text("# report", encoding="utf-8")
    return live, reports


def codes(findings):
    return {item["code"]: item["production"] for item in findings}


def look(mod, live, reports, disk_path, state=None, now=NOW, alive=None):
    """One look at a prepared site: observe + evaluate."""
    findings, new_state = mod.evaluate(mod.observe(live, reports, disk_path, now, alive or (lambda pid, started: True)),
                                       now, state or {})
    return findings, new_state


def run(mod, tmp_path, alive=None, state=None, now=NOW, disk_path=None, **kwargs):
    live, reports = site(tmp_path, now=now, **kwargs)
    return (*look(mod, live, reports, disk_path or tmp_path, state, now, alive), live, reports)


def webhook_config(tmp_path):
    config = tmp_path / "notify.local.json"
    config.write_text(json.dumps({"type": "webhook", "target": "https://example.invalid/hook"}), encoding="utf-8")
    return config


def cli(live, reports, tmp_path, state_file, config=None, disk_path=None):
    args = ["--live-dir", str(live), "--reports-dir", str(reports), "--disk-path", str(disk_path or tmp_path),
            "--state-file", str(state_file)]
    return args + (["--notify-config", str(config)] if config else ["--no-notify"])


def hourly(mod, tmp_path, capsys, hours, site_at=lambda hour: {}, alive=None, state_before=None):
    """Run the CLI once per hour from NOW, the state file carried from run to run.
    site_at(hour) gives the site's keyword arguments for that hour; state_before is
    {hour: what the state file holds before that run, None for "no file"}.
    → [(hour, exit code, output line, messages handed to the sender)]."""
    root, config, state_file = tmp_path / "hourly", webhook_config(tmp_path), tmp_path / "state.json"
    if state_file.exists():                     # every call starts from "the checker has never run"
        state_file.unlink()
    runs = []
    for hour in hours:
        now = NOW + timedelta(hours=hour)
        if hour in (state_before or {}):
            if state_file.exists():
                state_file.unlink()
            if state_before[hour] is not None:
                state_file.write_text(state_before[hour], encoding="utf-8")
        live, reports = site(tmp_path, root=root, now=now, **site_at(hour))
        sent = []
        rc = mod.main(cli(live, reports, tmp_path, state_file, config), now=now,
                      alive=alive or (lambda pid, started: True),
                      send=lambda channel, message: sent.append(message))
        runs.append((hour, rc, json.loads(capsys.readouterr().out), sent))
    return runs


