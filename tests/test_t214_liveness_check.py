def test_only_the_report_that_has_fallen_due_is_required(tmp_path):
    """B-1: before 22:30 UTC the report from two days ago is required, from 22:30 UTC on
    yesterday's. A report that has not fallen due yet is not a problem when it is absent."""
    mod = load()
    for clock, due in (((0, 0), "2026-11-22"), ((12, 0), "2026-11-22"), ((21, 56), "2026-11-22"),
                       ((22, 29), "2026-11-22"), ((22, 30), "2026-11-23"), ((23, 59), "2026-11-23")):
        now = datetime(2026, 11, 24, *clock, tzinfo=timezone.utc)
        generated = generated_reports(now)
        other = "2026-11-23" if due == "2026-11-22" else "2026-11-22"
        findings, *_ = run(mod, tmp_path, report=[d for d in generated if d != due], now=now)
        assert codes(findings) == {"report_missing": True}, clock        # really missing: the due one
        findings, *_ = run(mod, tmp_path, report=[d for d in generated if d != other], now=now)
        assert findings == [], (clock, codes(findings))                   # not due yet / no longer the latest due one


