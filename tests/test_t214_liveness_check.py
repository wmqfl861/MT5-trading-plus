def test_cli_prints_one_json_line_and_the_exit_code(tmp_path, capsys):
    mod = load()
    live, reports = site(tmp_path, report=False)
    state_file = tmp_path / "state.json"
    sent = []
    rc = mod.main(cli(live, reports, tmp_path, state_file, webhook_config(tmp_path)),
                  now=NOW, alive=lambda pid, started: True, send=lambda target, message: sent.append(message))
    out = capsys.readouterr().out
    assert rc == 3 and out.count("\n") == 1 and str(tmp_path) not in out
    result = json.loads(out)
    assert result["production"] is True and result["ok"] is False and result["notified"] == "sent"
    assert [item["code"] for item in result["findings"]] == ["report_missing"]
    assert len(sent) == 1 and sent[0] == "MT5 Demo 值守：report_missing(0分)"
    assert json.loads(state_file.read_text(encoding="utf-8")) == {"report_missing": NOW.isoformat()}


def test_a_failed_notification_does_not_lose_the_verdict(tmp_path, capsys):
    """S-1: a notification that cannot be sent leaves the verdict alone: exit code 3, findings
    printed as usual, plus notify_error (the exception class name only)."""
    mod = load()
    live, reports = site(tmp_path, report=False)
    state_file = tmp_path / "state.json"
    def unreachable(target, message):
        raise URLError(f"cannot reach {target} via {tmp_path}")   # the text carries a path: not echoed
    rc = mod.main(cli(live, reports, tmp_path, state_file, webhook_config(tmp_path)),
                  now=NOW, alive=lambda pid, started: True, send=unreachable)
    out = capsys.readouterr().out
    result = json.loads(out)
    assert rc == 3 and out.count("\n") == 1
    assert result["production"] is True and result["ok"] is False
    assert [item["code"] for item in result["findings"]] == ["report_missing"]
    assert result["notified"] == "failed" and result["notify_error"] == "URLError"
    assert str(tmp_path) not in out and "cannot reach" not in out


def test_an_unwritable_state_file_neither_loses_the_verdict_nor_blocks_the_notification(
        tmp_path, capsys, monkeypatch):
    """S-2: a state file that cannot be written (a full disk is exactly what the check should
    report): findings printed, notification still sent, exit code 3, plus state_error."""
    mod = load()
    live, reports = site(tmp_path, report=False)
    state_file = tmp_path / "state.json"
    def no_space(src, dst):
        raise OSError(28, f"No space left on device: {dst}")
    monkeypatch.setattr(mod.os, "replace", no_space)
    sent = []
    rc = mod.main(cli(live, reports, tmp_path, state_file, webhook_config(tmp_path)),
                  now=NOW, alive=lambda pid, started: True, send=lambda target, message: sent.append(message))
    out = capsys.readouterr().out
    result = json.loads(out)
    assert rc == 3 and [item["code"] for item in result["findings"]] == ["report_missing"]
    assert sent == ["MT5 Demo 值守：report_missing(0分)"] and result["notified"] == "sent"
    assert result["state_error"] == "OSError" and str(state_file) not in out and "No space" not in out


def test_exit_code_2_names_the_step_and_nothing_else(tmp_path, capsys, monkeypatch):
    """S-3: the check failing itself is exit code 2 and one fixed JSON line: step (from a fixed
    set) and the exception class name. No path, no exception text."""
    mod = load()
    live, reports = site(tmp_path)
    args = cli(live, reports, tmp_path, tmp_path / "state.json")
    rc = mod.main(args, now=NOW, alive=raising)                   # the probe fails inside observe
    out = capsys.readouterr().out
    assert rc == 2 and out.count("\n") == 1
    result = json.loads(out)
    assert result == {"ts": NOW.isoformat(), "ok": None, "error": "RuntimeError", "step": "observe"}
    assert result["step"] in ("observe", "evaluate", "notify", "state")
    monkeypatch.setattr(mod, "observe", lambda *args: {})         # a site of the wrong shape: evaluate fails
    rc = mod.main(args, now=NOW, alive=lambda pid, started: True)
    out = capsys.readouterr().out
    assert rc == 2
    assert json.loads(out) == {"ts": NOW.isoformat(), "ok": None, "error": "KeyError", "step": "evaluate"}
    assert "cannot open" not in out and str(tmp_path) not in out


def test_reason_text_is_never_output_or_sent(tmp_path, capsys):
    """S-4: the reason in halt.json and pause-*.json carries paths, logins and server names.
    Neither the output line nor the notification carries the text: only reason_present and
    reason_chars."""
    mod = load()
    reason = f"component_fatal: OSError: open {FAKE_PATH} login {FAKE_LOGIN} {FAKE_SERVER}"
    live, reports = site(tmp_path, halt=3700.0, pauses=[(902501, 3700.0)])
    for name in ("halt.json", "pause-902501.json"):
        path = live / name
        path.write_text(json.dumps({**json.loads(path.read_text(encoding="utf-8")), "reason": reason}),
                        encoding="utf-8")
    sent = []
    rc = mod.main(cli(live, reports, tmp_path, tmp_path / "state.json", webhook_config(tmp_path)),
                  now=NOW, alive=lambda pid, started: True, send=lambda target, message: sent.append(message))
    out = capsys.readouterr().out
    assert rc == 3 and len(sent) == 1                             # both past an hour: production-level
    for text in (out, sent[0]):
        for secret in (FAKE_PATH, FAKE_LOGIN, FAKE_SERVER, "component_fatal", reason[:80]):
            assert secret not in text
    by_code = {item["code"]: item for item in json.loads(out)["findings"]}
    for code in ("halt", "pause:902501"):
        assert by_code[code]["reason_present"] is True and by_code[code]["reason_chars"] == len(reason)
        assert "reason" not in by_code[code]
    (live / "halt.json").write_text(json.dumps({"owner": "risk", "ts": ago(NOW, 3700)}), encoding="utf-8")
    findings, _ = look(mod, live, reports, tmp_path)
    halted = next(item for item in findings if item["code"] == "halt")
    assert halted["reason_present"] is False and halted["reason_chars"] == 0


def test_unreadable_halt_and_pause_files_count_as_present(tmp_path, monkeypatch):
    """S-5: production is fail-closed for these files (halt.json present means halted, a pause
    file that cannot be read means paused). So is the check: a file that exists but cannot be
    read, parsed or shaped as expected counts as present, is graded as usual, and is flagged."""
    mod = load()
    not_json = ("", "{", "[", "null", '"text"', "123")
    cases = [("halt.json", "halt", content) for content in not_json]
    cases += [("pause-902610.json", "pause:902610", content) for content in
              (*not_json, '{"reason": "x"}', '{"magic": 902610, "paused": "yes"}')]
    for name, code, content in cases:
        live, reports = site(tmp_path)
        (live / name).write_text(content, encoding="utf-8")
        since = {code: (NOW - timedelta(seconds=3700)).isoformat()}          # there for over an hour
        findings, _ = look(mod, live, reports, tmp_path, since)
        assert codes(findings) == {code: True}, (name, content)
        assert findings[0]["unreadable"] is True and findings[0]["age_s"] is None, (name, content)
    live, reports = site(tmp_path)
    (live / "halt.json").write_text('{"reason": "x"}', encoding="utf-8")      # any object is a halt
    findings, _ = look(mod, live, reports, tmp_path, {"halt": (NOW - timedelta(seconds=3700)).isoformat()})
    assert codes(findings) == {"halt": True} and "unreadable" not in findings[0]
    live, reports = site(tmp_path)
    (live / "pause-902610.json").write_text(json.dumps({"magic": 902610, "paused": False}), encoding="utf-8")
    findings, _ = look(mod, live, reports, tmp_path)
    assert findings == []                                          # paused=false is "not paused"
    # Permission denied on halt.json: still present.
    live, reports = site(tmp_path)
    read_text = Path.read_text
    def denied(self, *args, **kwargs):
        if self.name == "halt.json":
            raise PermissionError(13, "Access is denied")
        return read_text(self, *args, **kwargs)
    monkeypatch.setattr(Path, "read_text", denied)
    findings, _ = look(mod, live, reports, tmp_path, {"halt": (NOW - timedelta(seconds=3700)).isoformat()})
    assert codes(findings) == {"halt": True} and findings[0]["unreadable"] is True
