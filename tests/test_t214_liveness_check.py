def test_malformed_registry_entries_are_registry_invalid_not_a_missing_role(tmp_path):
    """S-9: an entry the check cannot make sense of cannot be checked, and cannot prove the role
    is running either: one production-level registry_invalid finding, no role_missing for it, no
    crash. The well-formed entries are still checked."""
    mod = load()
    def registry_with(change):
        live, reports = site(tmp_path)
        doc = json.loads((live / "instances.json").read_text(encoding="utf-8"))
        change(doc)
        (live / "instances.json").write_text(json.dumps(doc), encoding="utf-8")
        return live, reports
    def edit(key, value):
        return lambda doc: doc["instances"][2].__setitem__(key, value)
    probed = []
    alive = lambda pid, started: probed.append(pid) or True
    risk_gone, nobody_gone = [11, 12, 14], [11, 12, 13, 14]
    for change, expected in ((edit("started_utc", None), risk_gone), (edit("pid", "13"), risk_gone),
                             (edit("pid", True), risk_gone), (edit("kind", None), risk_gone),
                             (lambda doc: doc["instances"][2].pop("started_utc"), risk_gone),
                             (lambda doc: doc["instances"].append("junk"), nobody_gone),
                             (lambda doc: doc["instances"].insert(0, None), nobody_gone)):
        live, reports = registry_with(change)
        findings, _ = look(mod, live, reports, tmp_path, alive=alive)
        assert codes(findings) == {"registry_invalid": True}
        assert sorted(probed) == expected, change                    # never asked about the malformed entry
        probed.clear()


