def test_webhook_sends_to_https_or_loopback_only_and_never_follows_redirects(monkeypatch):
    """S-12: https only; http only to a loopback address; a 3xx answer is not followed.
    Anything else is refused before any request is made. The transport is a stand-in."""
    mod = load()
    requests = []
    real_open = mod._open
    monkeypatch.setattr(mod, "_open", lambda request, timeout: requests.append(request) or _Response())
    loopback = str(ipaddress.ip_address(2130706433))                 # the IPv4 loopback address, built rather than typed out
    private = ".".join(str(part) for part in (10, 0, 0, 5))
