def test_webhook_sends_to_https_or_loopback_only_and_never_follows_redirects(monkeypatch):
    """S-12: https only; http only to a loopback address; a 3xx answer is not followed.
    Anything else is refused before any request is made. The transport is a stand-in."""
    mod = load()
    requests = []
    real_open = mod._open
    monkeypatch.setattr(mod, "_open", lambda request, timeout: requests.append(request) or _Response())
    loopback = str(ipaddress.ip_address(2130706433))                 # the IPv4 loopback address, built rather than typed out
    private = ".".join(str(part) for part in (10, 0, 0, 5))
    allowed = ("https://example.invalid/hook", f"http://{loopback}:8080/hook", "http://localhost:8080/hook",
               "http://[::1]:8080/hook")
    for target in allowed:
        mod.webhook_sender({"type": "webhook", "target": target}, "message")
    assert [(r.full_url, r.get_method(), json.loads(r.data)) for r in requests] == [
        (target, "POST", {"text": "message"}) for target in allowed]
    for target in (f"http://{private}/hook", "http://example.invalid/hook",
                   "ftp://example.invalid/x", "file:///x", "//example.invalid/hook", "https:///hook",
                   "http://[::1", "", None, 42, "javascript:alert(1)"):
        with pytest.raises(mod.RefusedTarget):
            mod.webhook_sender({"type": "webhook", "target": target}, "message")
    with pytest.raises(mod.RefusedTarget):
        mod.webhook_sender({"type": "webhook"}, "message")           # no target at all
    assert len(requests) == len(allowed)                             # nothing was sent for a refused target
    built = []
    class Opener:
        def open(self, request, timeout):
            return _Response()
    monkeypatch.setattr(urllib.request, "build_opener",
                        lambda *handlers: built.append(handlers) or Opener())
    real_open(urllib.request.Request(allowed[0], method="POST"), 15)        # the real _open, opener replaced
    assert len(built[0]) == 1 and built[0][0] is mod._NoRedirect           # _open builds its opener with it
    monkeypatch.undo()
    handlers = urllib.request.build_opener(mod._NoRedirect).handlers
    redirect = [h for h in handlers if isinstance(h, urllib.request.HTTPRedirectHandler)]
    assert [type(h) for h in redirect] == [mod._NoRedirect]                # the stock one is gone
    hop = (urllib.request.Request(allowed[0]), None, 302, "Found", {}, "https://other.invalid/")
    assert urllib.request.HTTPRedirectHandler().redirect_request(*hop) is not None
    assert redirect[0].redirect_request(*hop) is None                      # a 3xx answer is not followed


