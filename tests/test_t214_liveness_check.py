def test_supervisor_state_without_last_checked_is_dated_by_the_file(tmp_path):
    """S-13: the supervisor's refuse path and restart path write a state file without
    last_checked while it is checking every minute. Its age is the file's age, and the finding
    is named supervisor_state_stale, not "supervisor does not check"."""
    mod = load()
    for age, expected in ((30.0, {}), (700.0, {"supervisor_state_stale": True})):
        live, reports = site(tmp_path, supervisor_age=None)
        (live / "supervisor-state.json").write_text(json.dumps({"healthy_since": None}), encoding="utf-8")
        touch(live / "supervisor-state.json", NOW - timedelta(seconds=age))
        findings, _ = look(mod, live, reports, tmp_path)
