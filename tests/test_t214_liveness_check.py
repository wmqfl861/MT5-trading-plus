def test_a_malformed_state_file_starts_over_instead_of_exit_code_2(tmp_path, capsys, monkeypatch):
    """S-10: a state file of the wrong shape is voided: the check starts over, says so with
    state_reset, rewrites the file, and does not exit 2 every hour. One that cannot be read at
    all: the same, with the exception class name in the marker."""
    mod = load()
    live, reports = site(tmp_path)
    state_file = tmp_path / "state.json"
    wrong_shapes = ("[1, 2]", "null", "{}", '{"role_missing:risk": "2026-11-24T00:00:00+00:00"}',
                    '{"open": [], "recovered": {}}', '{"open": {"halt": {"since": "yesterday"}}, "recovered": {}}',
                    '{"open": {"halt": {"since": 5, "notified": null, "production": true}}, "recovered": {}}',
                    '{"open": {"halt": {"since": "2026-11-24T00:00:00+00:00", "production": true}}, "recovered": {}}',
                    '{"open": {}, "recovered": {"halt": "now"}}')
    def once():
        rc = mod.main(cli(live, reports, tmp_path, state_file), now=NOW, alive=lambda pid, started: True)
        return rc, json.loads(capsys.readouterr().out)
    for shape in wrong_shapes:
        state_file.write_text(shape, encoding="utf-8")
        rc, result = once()
        assert rc == 0 and result["findings"] == [] and result["state_reset"] is True, shape
        assert json.loads(state_file.read_text(encoding="utf-8")) == EMPTY_STATE, shape
    state_file.write_text('{"open": {', encoding="utf-8")             # half written
    rc, result = once()
    assert rc == 0 and result["state_reset"] == "JSONDecodeError"
    state_file.write_text("[]", encoding="utf-8")                     # empty: nothing was lost
    rc, result = once()
    assert rc == 0 and result["state_reset"] is None
    state_file.write_text(json.dumps(EMPTY_STATE), encoding="utf-8")  # a valid state is carried
    rc, result = once()
    assert rc == 0 and result["state_reset"] is None
    state_file.unlink()
    state_file.mkdir()                       # cannot be read at all (the class depends on the OS)
    rc, result = once()
    assert rc == 0 and result["state_reset"].endswith("Error") and result["state_error"]
    shutil.rmtree(state_file)
    def exploding(path):
        raise RuntimeError("boom")
    monkeypatch.setattr(mod, "load_state", exploding)                  # reading it fails in an unseen way
    rc, result = once()
    assert rc == 0 and result["state_reset"] == "RuntimeError" and result["state_error"] is None


