def test_timestamps_without_a_zone_are_read_as_utc(tmp_path, monkeypatch):
    """S-6: the project writes UTC; a timestamp without a zone is UTC too. Read as local time
    (the host is UTC+8) a five-second-old heartbeat is eight hours old, and in the registry a
    naive started_utc made every launcher look gone."""
    mod = load()
    live, reports = site(tmp_path)
    for kind, magic, _ in ROLES:
        path = live / f"heartbeat-{key_of(kind, magic)}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        data["ts"] = (NOW - timedelta(seconds=5)).replace(tzinfo=None).isoformat()
        path.write_text(json.dumps(data), encoding="utf-8")
    (live / "supervisor-state.json").write_text(json.dumps(
        {"last_checked": (NOW - timedelta(seconds=30)).replace(tzinfo=None).isoformat()}), encoding="utf-8")
    findings, _ = look(mod, live, reports, tmp_path)
    assert findings == []
    registry = json.loads((live / "instances.json").read_text(encoding="utf-8"))
    started = registry["instances"][0]["started_utc"]              # with its zone
    for entry in registry["instances"]:
        entry["started_utc"] = datetime.fromisoformat(entry["started_utc"]).replace(tzinfo=None).isoformat()
    (live / "instances.json").write_text(json.dumps(registry), encoding="utf-8")
    monkeypatch.setattr(mod, "process_started_utc", lambda pid: started)   # the process started when registered
    findings, _ = look(mod, live, reports, tmp_path, alive=mod.process_alive)
    assert findings == []


def test_a_timestamp_from_the_future_is_not_fresh(tmp_path):
    """S-6: a timestamp more than 60 s ahead of now is not fresh: its age is null and it gets a
    clock_ahead finding at production level. A skew of 60 s or less counts as 0."""
    mod = load()
    live, reports = site(tmp_path, halt=10.0)
    for key, seconds in (("902610", 600.0), ("902501", 30.0)):
        path = live / f"heartbeat-{key}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        data["ts"] = (NOW + timedelta(seconds=seconds)).isoformat()
        path.write_text(json.dumps(data), encoding="utf-8")
    ahead = (NOW + timedelta(hours=1)).isoformat()
    (live / "supervisor-state.json").write_text(json.dumps({"last_checked": ahead}), encoding="utf-8")
    (live / "halt.json").write_text(json.dumps({"reason": "x", "owner": "risk", "ts": ahead}), encoding="utf-8")
    touch(live / "halt.json", NOW - timedelta(seconds=10))
    findings, _ = look(mod, live, reports, tmp_path)
    by_code = codes(findings)
    assert by_code["clock_ahead:heartbeat-902610"] is True and by_code["heartbeat_stale:902610"] is False
    assert by_code["clock_ahead:supervisor"] is True and by_code["supervisor_state_stale"] is False
    assert by_code["clock_ahead:halt"] is True and by_code["halt"] is False
    assert not any(code.endswith(":902501") for code in by_code)       # 30 s ahead: fresh
    ages = {item["code"]: item.get("age_s") for item in findings}
    assert ages["heartbeat_stale:902610"] is None and ages["supervisor_state_stale"] is None
    # The checker's own clock went backwards since it wrote the state: no negative duration.
    findings, _ = look(mod, live, reports, tmp_path, {"halt": (NOW + timedelta(hours=2)).isoformat()})
    assert next(item for item in findings if item["code"] == "halt")["lasted_s"] == 0


