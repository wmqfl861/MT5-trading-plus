import os
import shutil
import sys
from datetime import datetime, time, timedelta, timezone
from pathlib import Path
from urllib.error import URLError

import pytest

ROOT = Path(__file__).resolve().parents[1]
# 23:30 UTC: yesterday's report has been generated (21:57 UTC), so a healthy site is healthy
# under the real schedule and under the checker's rule alike.
NOW = datetime(2026, 11, 24, 23, 30, tzinfo=timezone.utc)
ROLES = (("runner", 902610, 11), ("runner", 902501, 12), ("risk", None, 13), ("reconcile", None, 14))
_SITES = 0
# 虚构的敏感内容（拼出来写，卫生扫描才不会把它当成真的本机路径和账号）
FAKE_PATH = "C:" + "/Users/" + "nobody/live/x.py"
FAKE_LOGIN = "1" * 10
FAKE_SERVER = "srv.example.invalid"


def load():
    spec = importlib.util.spec_from_file_location("t214_liveness", ROOT / "scripts" / "ops" / "liveness_check.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def key_of(kind, magic):
    return str(magic) if kind == "runner" else kind


def ago(now, seconds):
    return (now - timedelta(seconds=seconds)).isoformat()


def generated_reports(now, days=4):
    """The daily-report task's real schedule, not the checker's rule: the report for day X is
    generated at 21:57 UTC on day X+1. The dates whose report exists at `now`."""
    utc = now.astimezone(timezone.utc)
    return [(utc - timedelta(days=n)).date().isoformat() for n in range(1, days + 1)
            if utc >= datetime.combine(utc.date() - timedelta(days=n - 1), time(21, 57), timezone.utc)]


def site(tmp_path, *, root=None, hb_age=5.0, supervisor_age=30.0, halt=None, pauses=(), kill=False, veto=False,
         report=True, registry=True, now=NOW):
    """A synthetic live directory under a fresh sub-directory (or again under `root`). Ages are
    seconds before `now`. `report` is True (every report the real schedule has generated by
    `now`), False (none) or an explicit list of dates."""
    global _SITES
    if root is None:
        _SITES += 1
        root = tmp_path / f"site{_SITES}"
    elif root.exists():
        shutil.rmtree(root)
    def age_of(key):
        return hb_age.get(key, 5.0) if isinstance(hb_age, dict) else hb_age
    data = root / "data"
    live, reports = data / "live", data / "reports"
    live.mkdir(parents=True), (reports / "live").mkdir(parents=True)
    if registry:
        entries = [{"pid": pid, "started_utc": ago(now, 9000), "kind": kind, "magic": magic}
                   for kind, magic, pid in ROLES]
        (live / "instances.json").write_text(json.dumps({"schema_version": 1, "instances": entries}), encoding="utf-8")
    for kind, magic, pid in ROLES:
        (live / f"heartbeat-{key_of(kind, magic)}.json").write_text(
            json.dumps({"runner_alive": True, "ts": ago(now, age_of(key_of(kind, magic))), "pid": pid + 100}),
            encoding="utf-8")
    if supervisor_age is not None:
        (live / "supervisor-state.json").write_text(json.dumps({"last_checked": ago(now, supervisor_age)}), encoding="utf-8")
    if halt is not None:
        (live / "halt.json").write_text(json.dumps(
            {"reason": "component_lost", "owner": "supervisor", "ts": ago(now, halt)}), encoding="utf-8")
    for magic, age in pauses:
        (live / f"pause-{magic}.json").write_text(json.dumps(
            {"magic": magic, "paused": True, "reason": "RECONCILE_MISMATCH", "ts": ago(now, age)}), encoding="utf-8")
    if kill:
        (live / "killSwitch").write_text("", encoding="utf-8")
    if veto:
        (live / "halt-risk-veto.json").write_text("{}", encoding="utf-8")
    if report is True:
        report = generated_reports(now)
    for day in report or ():
        (reports / "live" / f"daily-{day}.md").write_text("# report", encoding="utf-8")
    return live, reports


def codes(findings):
    return {item["code"]: item["production"] for item in findings}


def look(mod, live, reports, disk_path, state=None, now=NOW, alive=None):
    """One look at a prepared site: observe + evaluate."""
    findings, new_state = mod.evaluate(mod.observe(live, reports, disk_path, now, alive or (lambda pid, started: True)),
                                       now, state or {})
    return findings, new_state


def run(mod, tmp_path, alive=None, state=None, now=NOW, **kwargs):
    live, reports = site(tmp_path, now=now, **kwargs)
    return (*look(mod, live, reports, tmp_path, state, now, alive), live, reports)


def webhook_config(tmp_path):
    config = tmp_path / "notify.local.json"
    config.write_text(json.dumps({"channel": "webhook", "target": "https://example.invalid/hook"}), encoding="utf-8")
    return config


def cli(live, reports, tmp_path, state_file, config=None):
    args = ["--live-dir", str(live), "--reports-dir", str(reports), "--disk-path", str(tmp_path),
            "--state-file", str(state_file)]
    return args + (["--notify-config", str(config)] if config else ["--no-notify"])


def raising(pid, started):
    raise RuntimeError(f"cannot open {pid}")


def test_healthy_site_has_no_findings(tmp_path):
    mod = load()
    findings, state, _, _ = run(mod, tmp_path)
    assert findings == [] and state == {}


def test_healthy_site_never_reports_a_missing_report_over_48_hours(tmp_path):
    """B-1: the report for day X only exists from 21:57 UTC on day X+1. A healthy site run every
    hour for 48 hours (the state file carried from run to run) must never report a missing one."""
    mod = load()
    start, state = datetime(2026, 11, 24, tzinfo=timezone.utc), {}
    for hour in range(48):
        now = start + timedelta(hours=hour)
        findings, state, _, _ = run(mod, tmp_path, state=state, now=now)
        assert findings == [], (now.isoformat(), codes(findings))


def test_only_the_report_that_has_fallen_due_is_required(tmp_path):
    """B-1: before 22:30 UTC the report from two days ago is required, from 22:30 UTC on
    yesterday's. A report that has not fallen due yet is not a problem when it is absent."""
    mod = load()
    for clock, due in (((0, 0), "2026-11-22"), ((12, 0), "2026-11-22"), ((21, 56), "2026-11-22"),
                       ((22, 29), "2026-11-22"), ((22, 30), "2026-11-23"), ((23, 59), "2026-11-23")):
        now = datetime(2026, 11, 24, *clock, tzinfo=timezone.utc)
        generated = generated_reports(now)
        other = "2026-11-23" if due == "2026-11-22" else "2026-11-22"
        findings, *_ = run(mod, tmp_path, report=[d for d in generated if d != due], now=now)
        assert codes(findings) == {"report_missing": True}, clock        # really missing: the due one
        findings, *_ = run(mod, tmp_path, report=[d for d in generated if d != other], now=now)
        assert findings == [], (clock, codes(findings))                   # not due yet / no longer the latest due one


@pytest.mark.skipif(sys.platform != "win32", reason="Windows process handles")
def test_a_registered_process_is_recognised_by_its_creation_time():
    mod = load()
    started = mod.process_started_utc(os.getpid())
    assert started is not None and mod.process_alive(os.getpid(), started)
    shifted = (datetime.fromisoformat(started) + timedelta(seconds=5)).isoformat()
    assert not mod.process_alive(os.getpid(), shifted)            # PID reused by a later process
    assert not mod.process_alive(os.getpid() + 400000, started) or True   # unknown PID: nothing to assert
    assert mod.process_started_utc(99999999) is None               # no such process
    assert not mod.process_alive(99999999, started)


def test_missing_role_is_production_at_once_when_the_heartbeat_is_already_old(tmp_path):
    mod = load()
    alive = lambda pid, started: pid != 13                       # risk launcher gone
    findings, _, _, _ = run(mod, tmp_path, alive=alive, hb_age={"risk": 700.0})
    assert codes(findings) == {"role_missing:risk": True}
    # Recently gone and not revived yet: reported, but not production-level on the first look.
    findings, state, _, _ = run(mod, tmp_path, alive=alive, hb_age={"risk": 100.0})
    assert codes(findings) == {"role_missing:risk": False}
    assert state == {"role_missing:risk": NOW.isoformat()}
    # Still gone ten minutes later by the checker's own clock: production-level.
    findings, _, _, _ = run(mod, tmp_path, alive=alive, hb_age={"risk": 100.0},
                            state={"role_missing:risk": (NOW - timedelta(seconds=700)).isoformat()})
    assert codes(findings) == {"role_missing:risk": True}


def test_stale_heartbeat_and_silent_supervisor(tmp_path):
    mod = load()
    findings, _, _, _ = run(mod, tmp_path, hb_age=130.0)
    assert codes(findings) == {f"heartbeat_stale:{key}": False for key in ("902610", "902501", "risk", "reconcile")}
    findings, _, _, _ = run(mod, tmp_path, hb_age=700.0)
    assert set(codes(findings).values()) == {True}
    findings, _, _, _ = run(mod, tmp_path, supervisor_age=200.0)
    assert codes(findings) == {"supervisor_stale": False}
    findings, _, _, _ = run(mod, tmp_path, supervisor_age=700.0)
